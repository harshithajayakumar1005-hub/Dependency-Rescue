class NumberedCanvas(canvas.Canvas):
    """Adds running headers and footers with total page count."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 755, "DEPENDENCY RESCUE | Project Delay Prediction & Dependency Analysis Report")
            self.setStrokeColor(colors.HexColor("#CBD5E1"))
            self.setLineWidth(0.5)
            self.line(54, 748, 558, 748)

        # Footer
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 36, footer_text)
        self.drawString(54, 36, "CONFIDENTIAL - Generated by Dependency Rescue Engine")
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 48, 558, 48)
        self.restoreState()


class ReportGenerator:
    """Generates an executive PDF report with scheduling, AI risk predictions, and team updates."""

    def __init__(self, project_data, tasks_data, dependencies_data, cpm_data, risk_data, recovery_data, simulation_data=None, ai_data=None, daily_updates=None):
        self.project = project_data
        self.tasks = tasks_data
        self.dependencies = dependencies_data
        self.cpm = cpm_data
        self.risk = risk_data
        self.recovery = recovery_data
        self.simulation = simulation_data
        self.ai = ai_data
        self.daily_updates = daily_updates or []

    def build_pdf(self) -> bytes:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()
        
        # Custom palette
        primary_color = colors.HexColor("#0F172A")    # Deep Navy
        secondary_color = colors.HexColor("#6366F1")  # Indigo / Purple Accent
        text_dark = colors.HexColor("#1E293B")
        text_muted = colors.HexColor("#64748B")
        border_color = colors.HexColor("#E2E8F0")

        # Custom paragraph styles
        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=22,
            leading=26,
            textColor=primary_color,
            spaceAfter=4
        )

        subtitle_style = ParagraphStyle(
            'DocSubtitle',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=11,
            leading=14,
            textColor=secondary_color,
            spaceAfter=15
        )

        h1_style = ParagraphStyle(
            'Heading1Custom',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=13,
            leading=16,
            textColor=primary_color,
            spaceBefore=14,
            spaceAfter=8,
            keepWithNext=True
        )

        body_style = ParagraphStyle(
            'BodyCustom',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9,
            leading=12,
            textColor=text_dark
        )

        body_bold = ParagraphStyle(
            'BodyBoldCustom',
            parent=body_style,
            fontName='Helvetica-Bold'
        )

        table_header_style = ParagraphStyle(
            'TableHeader',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=8,
            leading=10,
            textColor=colors.white
        )

        table_cell_style = ParagraphStyle(
            'TableCell',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=8,
            leading=10,
            textColor=text_dark
        )

        story = []

        # Header Title
        story.append(Paragraph("DEPENDENCY RESCUE", title_style))
        story.append(Paragraph("Project Schedule Optimization & Delay Simulation Audit Report", subtitle_style))
        story.append(HRFlowable(width="100%", thickness=1.5, color=secondary_color, spaceBefore=0, spaceAfter=12))

        # --- SECTION 1: PROJECT OVERVIEW ---
        story.append(Paragraph("1. Project Overview", h1_style))
        total_tasks = len(self.tasks)
        completed_tasks = sum(1 for t in self.tasks if t.get('status') == 'Completed')
        completion_pct = int((completed_tasks / max(1, total_tasks)) * 100)

        overview_data = [
            [
                Paragraph("<b>Project Name:</b>", body_style), Paragraph(str(self.project.get('name', 'N/A')), body_style),
                Paragraph("<b>Project Status:</b>", body_style), Paragraph(str(self.project.get('status', 'Active')), body_style)
            ],
            [
                Paragraph("<b>Start Date:</b>", body_style), Paragraph(str(self.project.get('start_date', 'N/A')), body_style),
                Paragraph("<b>Project Deadline:</b>", body_style), Paragraph(str(self.project.get('deadline', 'N/A')), body_style)
            ],
            [
                Paragraph("<b>Total Tasks:</b>", body_style), Paragraph(f"{total_tasks} tasks ({completed_tasks} completed)", body_style),
                Paragraph("<b>Completion Rate:</b>", body_style), Paragraph(f"{completion_pct}%", body_style)
            ],
            [
                Paragraph("<b>Description:</b>", body_style),
                Paragraph(str(self.project.get('description', 'No description provided.')), body_style),
                Paragraph("<b>Report Date:</b>", body_style),
                Paragraph(datetime.now().strftime("%Y-%m-%d %H:%M"), body_style)
            ]
        ]

        t_overview = Table(overview_data, colWidths=[100, 160, 100, 144])
        t_overview.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#F8FAFC")),
            ('BOX', (0,0), (-1,-1), 0.5, border_color),
            ('INNERGRID', (0,0), (-1,-1), 0.5, border_color),
            ('TOPPADDING', (0,0), (-1,-1), 4),
            ('BOTTOMPADDING', (0,0), (-1,-1), 4),
        ]))
        story.append(t_overview)
        story.append(Spacer(1, 10))

        # --- SECTION 2: TASK DETAILS ---
        story.append(Paragraph("2. Task Details & Statuses", h1_style))
        task_table_data = [
            [
                Paragraph("ID", table_header_style),
                Paragraph("Task Name", table_header_style),
                Paragraph("Assignee", table_header_style),
                Paragraph("Dur (d)", table_header_style),
                Paragraph("Start Date", table_header_style),
                Paragraph("Deadline", table_header_style),
                Paragraph("Status", table_header_style),
                Paragraph("Priority", table_header_style)
            ]
        ]

        for t in self.tasks:
            task_table_data.append([
                Paragraph(str(t.get('id', '')), table_cell_style),
                Paragraph(t.get('name', 'N/A')[:28], table_cell_style),
                Paragraph(t.get('assignee_name') or 'Unassigned', table_cell_style),
                Paragraph(str(t.get('duration', 1)), table_cell_style),
                Paragraph(str(t.get('start_date', '')), table_cell_style),
                Paragraph(str(t.get('deadline', '')), table_cell_style),
                Paragraph(t.get('status', 'Not Started'), table_cell_style),
                Paragraph(t.get('priority', 'Medium'), table_cell_style),
            ])

        t_tasks = Table(task_table_data, colWidths=[24, 130, 80, 42, 64, 64, 55, 45])
        t_tasks.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), primary_color),
            ('GRID', (0, 0), (-1, -1), 0.5, border_color),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ]))
        story.append(t_tasks)
        story.append(Spacer(1, 10))

        # --- SECTION 3: DEPENDENCY ANALYSIS ---
        story.append(Paragraph("3. Dependency Analysis (Directed Graph Representation)", h1_style))
        task_name_map = {t['id']: t['name'] for t in self.tasks}
        dep_data = [
            [
                Paragraph("Predecessor Task", table_header_style),
                Paragraph("Relationship", table_header_style),
                Paragraph("Successor (Dependent) Task", table_header_style)
            ]
        ]

        if not self.dependencies:
            dep_data.append([Paragraph("No dependencies defined.", table_cell_style), Paragraph("-", table_cell_style), Paragraph("-", table_cell_style)])
        else:
            for d in self.dependencies:
                p_name = task_name_map.get(d['predecessor_id'], f"Task #{d['predecessor_id']}")
                s_name = task_name_map.get(d['successor_id'], f"Task #{d['successor_id']}")
                dep_data.append([
                    Paragraph(f"#{d['predecessor_id']} - {p_name}", table_cell_style),
                    Paragraph("─── Finishes before ───►", table_cell_style),
                    Paragraph(f"#{d['successor_id']} - {s_name}", table_cell_style)
                ])

        t_deps = Table(dep_data, colWidths=[200, 104, 200])
        t_deps.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#334155")),
            ('GRID', (0, 0), (-1, -1), 0.5, border_color),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ]))
        story.append(t_deps)
        story.append(Spacer(1, 10))

        # --- SECTION 4: CRITICAL PATH ANALYSIS ---
        story.append(Paragraph("4. Critical Path Analysis (CPM)", h1_style))
        crit_tasks = self.cpm.get("critical_task_ids", [])
        crit_names = [task_name_map.get(cid, f"#{cid}") for cid in crit_tasks]
        crit_path_str = "  ➔  ".join(crit_names) if crit_names else "None"

        cpm_summary_data = [
            [
                Paragraph("<b>Critical Path Duration:</b>", body_style), Paragraph(f"{self.cpm.get('project_duration_days', 0)} Working Days", body_style),
                Paragraph("<b>Critical Tasks Count:</b>", body_style), Paragraph(f"{len(crit_tasks)} Tasks (Zero Float)", body_style)
            ],
            [
                Paragraph("<b>Critical Path Sequence:</b>", body_style),
                Paragraph(crit_path_str, body_style),
                Paragraph("<b>Calculated Finish:</b>", body_style),
                Paragraph(str(self.cpm.get('estimated_finish_date', 'N/A')), body_style)
            ]
        ]
        t_cpm_summary = Table(cpm_summary_data, colWidths=[120, 140, 110, 134])
        t_cpm_summary.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#F1F5F9")),
            ('BOX', (0,0), (-1,-1), 0.5, border_color),
            ('INNERGRID', (0,0), (-1,-1), 0.5, border_color),
            ('TOPPADDING', (0,0), (-1,-1), 3),
            ('BOTTOMPADDING', (0,0), (-1,-1), 3),
        ]))
        story.append(t_cpm_summary)
        story.append(Spacer(1, 6))

        cpm_table_data = [
            [
                Paragraph("Task", table_header_style),
                Paragraph("Dur", table_header_style),
                Paragraph("ES (d)", table_header_style),
                Paragraph("EF (d)", table_header_style),
                Paragraph("LS (d)", table_header_style),
                Paragraph("LF (d)", table_header_style),
                Paragraph("Total Float", table_header_style),
                Paragraph("Critical?", table_header_style)
            ]
        ]

        task_schedules = self.cpm.get("task_schedules", {})
        for tid, sched in task_schedules.items():
            is_crit = sched["is_critical"]
            crit_badge = "CRITICAL (0d)" if is_crit else f"{sched['total_float']}d slack"
            cpm_table_data.append([
                Paragraph(f"#{tid} {sched['name'][:24]}", table_cell_style),
                Paragraph(str(sched['duration']), table_cell_style),
                Paragraph(str(sched['es_days']), table_cell_style),
                Paragraph(str(sched['ef_days']), table_cell_style),
                Paragraph(str(sched['ls_days']), table_cell_style),
                Paragraph(str(sched['lf_days']), table_cell_style),
                Paragraph(str(sched['total_float']), table_cell_style),
                Paragraph(crit_badge, table_cell_style)
            ])

        t_cpm_details = Table(cpm_table_data, colWidths=[150, 36, 42, 42, 42, 42, 66, 84])
        t_cpm_details.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), secondary_color),
            ('GRID', (0, 0), (-1, -1), 0.5, border_color),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ]))
        story.append(t_cpm_details)
        story.append(Spacer(1, 10))

        # --- SECTION 5: DELAY SIMULATION RESULTS ---
        story.append(Paragraph("5. Delay Simulation Results (What-If Scenario)", h1_style))
        if self.simulation:
            sel_task = self.simulation.get("selected_task", {})
            sim_sum = self.simulation.get("summary", {})
            sim_desc_data = [
                [
                    Paragraph("<b>Simulated Task:</b>", body_style), Paragraph(f"#{sel_task.get('id')} {sel_task.get('name')}", body_style),
                    Paragraph("<b>Hypothetical Delay:</b>", body_style), Paragraph(f"+{sel_task.get('delay_days')} Days", body_style)
                ],
                [
                    Paragraph("<b>Directly Affected:</b>", body_style), Paragraph(f"{sim_sum.get('direct_affected_count', 0)} Tasks", body_style),
                    Paragraph("<b>Indirectly Affected:</b>", body_style), Paragraph(f"{sim_sum.get('indirect_affected_count', 0)} Tasks", body_style)
                ],
                [
                    Paragraph("<b>Total Affected:</b>", body_style), Paragraph(f"{sim_sum.get('total_affected_count', 0)} Downstream Tasks", body_style),
                    Paragraph("<b>Project Delay:</b>", body_style), Paragraph(f"+{sim_sum.get('total_project_delay_days', 0)} Days Slip", body_style)
                ],
                [
                    Paragraph("<b>New Completion Date:</b>", body_style), Paragraph(str(sim_sum.get('simulated_finish_date')), body_style),
                    Paragraph("<b>Deadline Breached:</b>", body_style), Paragraph("YES (OVERDUE)" if sim_sum.get('deadline_breached') else "NO (Within Buffer)", body_style)
                ]
            ]
            t_sim_summary = Table(sim_desc_data, colWidths=[110, 142, 110, 142])
            t_sim_summary.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#FEF3C7" if sim_sum.get('deadline_breached') else "#F0FDF4")),
                ('BOX', (0,0), (-1,-1), 0.5, border_color),
                ('INNERGRID', (0,0), (-1,-1), 0.5, border_color),
                ('TOPPADDING', (0,0), (-1,-1), 3),
                ('BOTTOMPADDING', (0,0), (-1,-1), 3),
            ]))
            story.append(t_sim_summary)
        else:
            story.append(Paragraph("<i>No active delay simulation loaded. Run a What-If simulation to audit downstream slip.</i>", body_style))
        story.append(Spacer(1, 10))

        # --- SECTION 6: BASELINE VS SIMULATED SCHEDULE ---
        story.append(Paragraph("6. Baseline vs. Simulated Schedule Comparison", h1_style))
        if self.simulation and "task_comparisons" in self.simulation:
            comp_table_data = [
                [
                    Paragraph("Task", table_header_style),
                    Paragraph("Base Start", table_header_style),
                    Paragraph("Base End", table_header_style),
                    Paragraph("Sim Start", table_header_style),
                    Paragraph("Sim End", table_header_style),
                    Paragraph("Slip", table_header_style),
                    Paragraph("Impact Type", table_header_style)
                ]
            ]
            for tc in self.simulation["task_comparisons"]:
                slip = f"+{tc['delay_experienced_days']}d" if tc['delay_experienced_days'] > 0 else "0d"
                comp_table_data.append([
                    Paragraph(f"#{tc['task_id']} {tc['name'][:22]}", table_cell_style),
                    Paragraph(tc['baseline_start'], table_cell_style),
                    Paragraph(tc['baseline_end'], table_cell_style),
                    Paragraph(tc['simulated_start'], table_cell_style),
                    Paragraph(tc['simulated_end'], table_cell_style),
                    Paragraph(slip, table_cell_style),
                    Paragraph(tc['impact_type'], table_cell_style),
                ])

            t_comp = Table(comp_table_data, colWidths=[130, 62, 62, 62, 62, 42, 84])
            t_comp.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1E293B")),
                ('GRID', (0, 0), (-1, -1), 0.5, border_color),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
                ('TOPPADDING', (0, 0), (-1, -1), 3),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
            ]))
            story.append(t_comp)
        else:
            story.append(Paragraph("<i>Baseline schedule active. All tasks currently aligned with planned milestones.</i>", body_style))
        story.append(Spacer(1, 10))

        # --- SECTION 7: DEADLINE RISK ANALYSIS ---
        story.append(Paragraph("7. Deadline Risk Analysis", h1_style))
        risk_lvl = self.risk.get("overall_risk_level", "LOW")
        risk_score = self.risk.get("risk_score", 10)
        risk_color = colors.HexColor("#EF4444" if risk_lvl == "CRITICAL" else ("#F97316" if risk_lvl == "HIGH" else ("#F59E0B" if risk_lvl == "MEDIUM" else "#10B981")))

        risk_overview_data = [
            [
                Paragraph("<b>Overall Risk Level:</b>", body_style), Paragraph(f"<b>{risk_lvl}</b> (Score: {risk_score}/100)", body_style),
                Paragraph("<b>Overdue Tasks:</b>", body_style), Paragraph(f"{self.risk.get('overdue_tasks_count', 0)} Tasks", body_style)
            ],
            [
                Paragraph("<b>Risk Explanation:</b>", body_style),
                Paragraph(str(self.risk.get('explanation', 'N/A')), body_style),
                Paragraph("<b>Slack Buffer:</b>", body_style),
                Paragraph(f"{self.risk.get('deadline_slack_days', 'N/A')} Days", body_style)
            ]
        ]
        t_risk = Table(risk_overview_data, colWidths=[110, 142, 100, 152])
        t_risk.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#F8FAFC")),
            ('BOX', (0,0), (-1,-1), 1, risk_color),
            ('INNERGRID', (0,0), (-1,-1), 0.5, border_color),
            ('TOPPADDING', (0,0), (-1,-1), 3),
            ('BOTTOMPADDING', (0,0), (-1,-1), 3),
        ]))
        story.append(t_risk)
        story.append(Spacer(1, 6))

        # Risk factors table
        factors = self.risk.get("risk_factors", [])
        if factors:
            factor_table_data = [[
                Paragraph("Identified Risk Factor", table_header_style),
                Paragraph("Severity", table_header_style),
                Paragraph("Detailed Impact Assessment", table_header_style)
            ]]
            for rf in factors:
                factor_table_data.append([
                    Paragraph(rf.get('factor', 'Risk'), table_cell_style),
                    Paragraph(rf.get('severity', 'Medium'), table_cell_style),
                    Paragraph(rf.get('description', ''), table_cell_style),
                ])
            t_factors = Table(factor_table_data, colWidths=[140, 70, 294])
            t_factors.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#475569")),
                ('GRID', (0, 0), (-1, -1), 0.5, border_color),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
                ('TOPPADDING', (0, 0), (-1, -1), 3),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
            ]))
            story.append(t_factors)
        story.append(Spacer(1, 10))

        # --- SECTION 8: RECOVERY SUGGESTIONS ---
        story.append(Paragraph("8. Actionable Recovery Suggestions", h1_style))
        rec_table_data = [
            [
                Paragraph("ID", table_header_style),
                Paragraph("Strategy & Action", table_header_style),
                Paragraph("Priority", table_header_style),
                Paragraph("Mathematical Justification & Expected Recovery Impact", table_header_style)
            ]
        ]

        for r in self.recovery:
            combined_desc = f"<b>{r.get('title', '')}</b><br/>{r.get('recommendation', '')}<br/><i>Reason:</i> {r.get('reason', '')}<br/><b>Impact:</b> {r.get('expected_impact', '')}"
            rec_table_data.append([
                Paragraph(r.get('id', 'REC'), table_cell_style),
                Paragraph(r.get('type', 'Recovery'), table_cell_style),
                Paragraph(r.get('priority', 'Medium'), table_cell_style),
                Paragraph(combined_desc, table_cell_style),
            ])

        t_recovery = Table(rec_table_data, colWidths=[40, 104, 50, 310])
        t_recovery.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), primary_color),
            ('GRID', (0, 0), (-1, -1), 0.5, border_color),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(t_recovery)

        # Build document with running page numbers
        doc.build(story, canvasmaker=NumberedCanvas)
        buffer.seek(0)
        return buffer.getvalue()

